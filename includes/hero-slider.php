<!-- Slider Logic Script (Autoplay + Desktop Arrows + Pause on Hover) -->
<script>
  document.addEventListener('DOMContentLoaded', () => {
    const slides = document.querySelectorAll('#home .hero-item');
    const dots = document.querySelectorAll('#home .hero-dot');
    const prevBtn = document.getElementById('heroPrevBtn');
    const nextBtn = document.getElementById('heroNextBtn');
    const heroSection = document.getElementById('home');

    if (!slides.length) return;

    let currentIndex = 0;
    const totalSlides = slides.length;
    let autoPlayTimer = null;

    function goToSlide(index) {
      // Normalize index
      if (index >= totalSlides) index = 0;
      if (index < 0) index = totalSlides - 1;
      currentIndex = index;

      // Update Slides
      slides.forEach((slide, i) => {
        if (i === currentIndex) {
          slide.classList.remove('opacity-0', 'pointer-events-none', 'z-0');
          slide.classList.add('opacity-100', 'z-10');
        } else {
          slide.classList.remove('opacity-100', 'z-10');
          slide.classList.add('opacity-0', 'pointer-events-none', 'z-0');
        }
      });

      // Update Dots
      dots.forEach((dot, i) => {
        if (i === currentIndex) {
          dot.classList.remove('w-3', 'bg-white/40');
          dot.classList.add('w-8', 'bg-[#FF7A00]');
        } else {
          dot.classList.remove('w-8', 'bg-[#FF7A00]');
          dot.classList.add('w-3', 'bg-white/40');
        }
      });
    }

    function nextSlide() {
      goToSlide(currentIndex + 1);
    }

    function prevSlide() {
      goToSlide(currentIndex - 1);
    }

    // Auto Play Interval (5.5 Seconds)
    function startAutoPlay() {
      stopAutoPlay();
      autoPlayTimer = setInterval(nextSlide, 5500);
    }

    function stopAutoPlay() {
      if (autoPlayTimer) clearInterval(autoPlayTimer);
    }

    // Event Listeners
    if (nextBtn) {
      nextBtn.addEventListener('click', () => {
        nextSlide();
        startAutoPlay();
      });
    }

    if (prevBtn) {
      prevBtn.addEventListener('click', () => {
        prevSlide();
        startAutoPlay();
      });
    }

    dots.forEach((dot, idx) => {
      dot.addEventListener('click', () => {
        goToSlide(idx);
        startAutoPlay();
      });
    });

    // Pause on desktop mouse hover, resume on mouse leave
    heroSection.addEventListener('mouseenter', stopAutoPlay);
    heroSection.addEventListener('mouseleave', startAutoPlay);

    // Initial Start
    startAutoPlay();

    // Reinitialize Lucide Icons if available
    if (window.lucide) {
      lucide.createIcons();
    }
  });
</script>