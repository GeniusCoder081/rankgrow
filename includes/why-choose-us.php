<!-- Smooth Tab Switch Script -->
<script>
  document.addEventListener('DOMContentLoaded', () => {
    const tabBtns = document.querySelectorAll('#whyTabsNav .tab-btn');
    const tabContents = document.querySelectorAll('#whyChooseUs .tab-content');

    tabBtns.forEach(btn => {
      btn.addEventListener('click', () => {
        tabBtns.forEach(b => {
          b.classList.remove('bg-[#FF7A00]', 'text-white', 'shadow-lg', 'shadow-[#FF7A00]/25', 'border-transparent');
          b.classList.add('bg-slate-900/80', 'text-slate-300', 'border-slate-800');
        });
        btn.classList.add('bg-[#FF7A00]', 'text-white', 'shadow-lg', 'shadow-[#FF7A00]/25', 'border-transparent');
        btn.classList.remove('bg-slate-900/80', 'text-slate-300', 'border-slate-800');

        const target = btn.getAttribute('data-tab');
        tabContents.forEach(tc => {
          if (tc.id === target) {
            tc.classList.remove('hidden');
            tc.classList.add('opacity-0', 'translate-y-2');
            setTimeout(() => {
              tc.classList.remove('opacity-0', 'translate-y-2');
              tc.classList.add('opacity-100', 'translate-y-0');
            }, 20);
          } else {
            tc.classList.add('hidden');
          }
        });
      });
    });

    if (window.lucide) {
      lucide.createIcons();
    }
  });
</script>